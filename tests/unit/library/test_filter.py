from pathlib import Path

import pytest

from lies.library.filter import (
    should_skip_content,
    should_skip_filename,
)


@pytest.mark.parametrize(
    "filename",
    [
        "LICENSE",
        "license",
        "License.md",
        "CONTRIBUTING",
        "notice",
        "NOTICE",
        "code_of_conduct.md",
        "README.md",
        "redirects.md",
        "template.md",
        "build_staging.md",
        "CHANGELOG.md",
        "changelog-2024.md",
        "code-of-conduct.md",
        "credits.md",
        "authors.md",
        "maintainers.md",
    ],
)
def test_skip_filename_built_ins(tmp_path: Path, filename: str) -> None:
    assert should_skip_filename(tmp_path / filename) is not None


def test_skip_filename_normal_passes(tmp_path: Path) -> None:
    assert should_skip_filename(tmp_path / "guide.md") is None


def test_skip_filename_extra_stems(tmp_path: Path) -> None:
    assert (
        should_skip_filename(tmp_path / "robots.txt.md", extra_stems={"robots.txt.md"}) is not None
    )


@pytest.mark.parametrize(
    "body,expected",
    [
        (
            "THIS IS AN AUTOGENERATED FILE. do not edit\n\nmore content\n",
            "skip-content:autogenerated:",
        ),
        ("{% extends 'base.html' %}\nbody\n", "skip-content:template-artifact:"),
        ("line1\nline2\n", "skip-content:thin-content:"),
    ],
)
def test_skip_content(body: str, expected: str) -> None:
    reason = should_skip_content(body)
    assert reason is not None
    assert reason.startswith(expected)


def test_skip_content_full_prefix_thin_content() -> None:
    reason = should_skip_content("line1\nline2\n")
    assert reason == "skip-content:thin-content:2"


def test_skip_content_full_prefix_autogenerated() -> None:
    body = "THIS IS AN AUTOGENERATED FILE. do not edit\n\nmore content\n"
    reason = should_skip_content(body)
    assert reason is not None
    assert reason.startswith("skip-content:autogenerated:THIS IS AN AUTOGENERATED")


def test_skip_content_full_prefix_template_artifact() -> None:
    body = "{% extends 'base.html' %}\nbody\n"
    reason = should_skip_content(body)
    assert reason is not None
    assert reason.startswith("skip-content:template-artifact:{% extends")


def test_skip_content_normal_passes() -> None:
    assert should_skip_content("\n".join(f"line {i}" for i in range(20))) is None


def test_skip_content_fenced_marker_ignored() -> None:
    body = "intro\n\n```\nTHIS IS AN AUTOGENERATED FILE\n```\n\n" + "\n".join(
        f"l{i}" for i in range(20)
    )
    assert should_skip_content(body) is None
