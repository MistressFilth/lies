"""Skip gates for library ingest: filename + content filters."""

from __future__ import annotations

import re
from collections.abc import Container, Iterable
from pathlib import Path

FILENAME_SKIP_STEMS: frozenset[str] = frozenset(
    {
        "license",
        "contributing",
        "contributions",
        "code_of_conduct",
        "code-of-conduct",
        "credits",
        "authors",
        "notice",
        "maintainers",
        "readme",
        "redirects",
        "new_index_prompt",
        "reindex_prompt",
        "template",
        "build_staging",
    }
)

FILENAME_SKIP_PREFIXES: tuple[str, ...] = ("changelog",)

_AUTOGEN_MARKERS = (
    "THIS IS AN AUTOGENERATED FILE",
    "DO NOT EDIT THIS FILE DIRECTLY",
    "auto-generated by",
)
_JINJA_MARKERS = ("{% block", "{% extends", "{% macro")
_MIN_CONTENT_LINES = 5

_FENCED_CODE_BLOCK = re.compile(r"^(```|~~~).*?^\1", re.MULTILINE | re.DOTALL)


def should_skip_filename(
    path: Path,
    *,
    extra_stems: Container[str] = (),
    extra_prefixes: Container[str] = (),
) -> str | None:
    filename = path.name.lower()
    stem = path.stem.lower()
    if stem in FILENAME_SKIP_STEMS or filename in extra_stems or stem in extra_stems:
        return f"skip-stem:{stem}"
    for prefix in (*FILENAME_SKIP_PREFIXES, *_iterable_prefixes(extra_prefixes)):
        if stem.startswith(prefix):
            return f"skip-stem-prefix:{prefix}"
    return None


def _iterable_prefixes(prefixes: Container[str]) -> Iterable[str]:
    yield from prefixes


def _strip_fenced(content: str) -> str:
    return _FENCED_CODE_BLOCK.sub("", content)


def should_skip_content(body: str) -> str | None:
    stripped = _strip_fenced(body)
    upper = stripped[:2000].upper()
    for marker in _AUTOGEN_MARKERS:
        if marker.upper() in upper:
            return f"autogenerated:{marker[:30]}"
    for marker in _JINJA_MARKERS:
        if marker in stripped[:2000]:
            return f"template-artifact:{marker}"
    non_blank = [ln for ln in body.splitlines() if ln.strip()]
    if len(non_blank) <= _MIN_CONTENT_LINES:
        return f"thin-content:{len(non_blank)}"
    return None


__all__ = (
    "FILENAME_SKIP_STEMS",
    "FILENAME_SKIP_PREFIXES",
    "should_skip_filename",
    "should_skip_content",
)
